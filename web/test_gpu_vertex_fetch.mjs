import assert from 'node:assert/strict';
import {decodeVertex,vertexFormat} from './gpu-draw.mjs';
let checks=0;
const check=(nvn,bytes,expected)=>{const data=new DataView(Uint8Array.from(bytes).buffer);assert.deepEqual(decodeVertex(data,0,nvn),expected);checks++;};
check(1,[255],[1,0,0,1]);
check(2,[128],[-1,0,0,1]);
check(3,[255],[255,0,0,1]);
check(4,[128],[-128,0,0,1]);
check(5,[0,0xbc],[-1,0,0,1]);
check(5,[1,0],[2**-24,0,0,1]);
check(5,[0,0x7c],[Infinity,0,0,1]);
check(6,[255,255],[1,0,0,1]);
check(7,[0,128],[-1,0,0,1]);
check(8,[255,255],[65535,0,0,1]);
check(9,[0,128],[-32768,0,0,1]);
check(10,[0,0,128,63],[1,0,0,1]);
check(11,[255,255,255,255],[4294967295,0,0,1]);
check(12,[0,0,0,128],[-2147483648,0,0,1]);
check(0x5e,[255,2,128],[-1,2,-128,1]);
check(0x55,[255,255,255,255],[4294967295,0,0,1]);
check(0x56,[0,0,0,128],[-2147483648,0,0,1]);
check(0x3d,[255,255,255,255],[1,1,1,1]);
check(0x3e,[255,255,255,255],[1023,1023,1023,3]);
check(0x69,[0,2,8,160],[-1,-1,-1,-1]);
check(0x6a,[255,255,255,255],[-1,-1,-1,-1]);
check(0x6b,[255,255,255,255],[1023,1023,1023,3]);
check(0x6c,[0,2,8,160],[-512,-512,-512,-2]);
for(const nvn of [1,2,3,4,5,6,7,8,9,0x1d,0x1f,0x5e]){assert.equal(vertexFormat(nvn).format,null);checks++;}
assert.equal(vertexFormat(0x22).format,'float32x3');checks++;
assert.equal(vertexFormat(0x78).format,'sint32x4');checks++;
assert.throws(()=>vertexFormat(0xff),/Unknown NVN/);checks++;
console.log(`NVN vertex fetch: PASS (${checks} boundary/default/type contracts)`);
