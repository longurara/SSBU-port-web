import assert from 'node:assert/strict';
import {findGuestPoolTable,readGuestGpuPools,describeGuestBufferRange,installGuestPoolDiagnostics} from './gpu-guest-pool-diagnostics.mjs';
const heap=new Uint8Array(256*1024),v=new DataView(heap.buffer),base=0x4000,pointer=0x18000;
const key=0x7100006000n,memory=0x8000000000n,gpuAddress=0x7b00000000n;
const bucket=Number(((key>>4n)*2654435761n)&4095n);
v.setUint32(base+bucket*4,pointer,true);v.setBigUint64(pointer,key,true);v.setBigUint64(pointer+8,memory,true);
v.setBigUint64(pointer+16,4096n,true);v.setBigUint64(pointer+40,gpuAddress,true);
v.setUint32(pointer+48,1,true);v.setUint32(pointer+56,7,true);
const buffers=new Map([[7,{size:4096}]]),options={searchBytes:65536},before=heap.slice();
assert.equal(findGuestPoolTable(heap,buffers,options),base);
const pools=readGuestGpuPools(heap,buffers,base);
assert.deepEqual(pools,[{gpuHandle:7,key:'0x7100006000',memory:'0x8000000000',gpuAddress:'0x7b00000000',size:4096,flags:0}]);
const mappings=new Map([[7,pools[0]],[8,{...pools[0],memory:'0x0'}]]);
assert.equal(describeGuestBufferRange(mappings,[7,256,560]).guestAddress,'0x8000000100');
assert.equal(describeGuestBufferRange(mappings,[8,256,560]).guestAddress,null);
assert.equal(describeGuestBufferRange(mappings,[7,4095,2]),null);
assert.equal(describeGuestBufferRange(mappings,[99,0,4]),null);
assert.equal(describeGuestBufferRange(mappings,[7,-1,4]),null);
assert.deepEqual(heap,before); // Inspector cannot alter program data.
v.setUint32(pointer+72,pointer,true);assert.throws(()=>readGuestGpuPools(heap,buffers,base),/validation failed/);
v.setUint32(pointer+72,0,true);assert.equal(findGuestPoolTable(heap,new Map([[7,{size:8192}]]),options),null);
heap.copyWithin(0x9000,base,base+16384);assert.throws(()=>findGuestPoolTable(heap,buffers,options),/Ambiguous/);
heap.fill(0,0x9000,0xd000);assert.throws(()=>findGuestPoolTable(heap,buffers,{searchBytes:65536*1024}),/budget/);
let calls=0;const backend={buffers,request(){calls++;return Promise.resolve({ok:true});}},original=backend.request;
const diagnostic=installGuestPoolDiagnostics(backend,()=>heap);
await backend.request(2,{handle:7});assert.equal(calls,1);assert.equal(diagnostic.report().pools.length,1);
assert.deepEqual(heap,before);diagnostic.close();assert.equal(backend.request,original);
const invalid=installGuestPoolDiagnostics(backend,()=>null);await backend.request(2,{handle:7});
assert.equal(calls,2);assert.equal(invalid.report().errors.length,1);invalid.close();
console.log('Guest GPU pool diagnostics: PASS (18 contracts; read-only discovery, source ranges, ambiguity, malformed records, nonfatal diagnostics and cleanup)');
